// Development tool: how much of the math in Markdown files SwiftMath can
// typeset (after MathMacros), and which commands still fail.
//   build/math-coverage FILE.md... [--list] [--min PERCENT] [--report OUT.md]
// --report writes the failures as a Markdown page (source next to how the
// preview draws it), e.g. examples/math-unsupported.md.
import AppKit

var files: [String] = []
var list = false
var minimum: Double?
var report: String?
var args = CommandLine.arguments.dropFirst().makeIterator()
while let arg = args.next() {
    switch arg {
    case "--list": list = true
    case "--min": minimum = args.next().flatMap(Double.init)
    case "--report": report = args.next()
    default: files.append(arg)
    }
}
guard !files.isEmpty else {
    print("usage: math-coverage FILE.md... [--list] [--min PERCENT] [--report OUT.md]")
    exit(2)
}

// Every extra symbol must exist in the math font, or it would draw nothing.
MathSupport.warmUp()
let font: CTFont = MTFontManager.fontManager.latinModernFont(withSize: 15)!.ctFont
var missing: [String] = []
for (name, _, value) in MathMacros.symbols {
    let utf16 = Array(value.utf16)
    var glyphs = [CGGlyph](repeating: 0, count: utf16.count)
    if !CTFontGetGlyphsForCharacters(font, utf16, &glyphs, utf16.count) { missing.append("\\\(name) \(value)") }
}
if !missing.isEmpty { print("symbols missing from Latin Modern Math: " + missing.joined(separator: ", ")) }

var total = 0
var failures: [(String, String)] = []
for file in files {
    let url = URL(fileURLWithPath: file)
    guard let data = try? Data(contentsOf: url),
          let doc = Renderer.native(markdown: data, baseDirectory: url.deletingLastPathComponent()) else {
        print("cannot render \(file)")
        exit(1)
    }
    for run in doc.runs where run.flags & NativeDocument.RunFlag.attachment != 0
        && (run.a == NativeDocument.AttachmentKind.mathInline || run.a == NativeDocument.AttachmentKind.mathDisplay) {
        let latex = doc.strings[safe: Int(run.b)] ?? ""
        total += 1
        if MathSupport.parse(latex) == nil {
            var error: NSError?
            _ = MTMathListBuilder.build(fromString: MathMacros.expand(latex), error: &error)
            failures.append((latex, error?.localizedDescription ?? "no result"))
        }
    }
}

let ok = total - failures.count
let percent = total == 0 ? 100 : Double(ok) / Double(total) * 100
print(String(format: "%d formulas, %d typeset (%.1f%%), %d fail", total, ok, percent, failures.count))
var reasons: [String: Int] = [:]
for (_, reason) in failures { reasons[reason, default: 0] += 1 }
for (reason, count) in reasons.sorted(by: { $0.value > $1.value || ($0.value == $1.value && $0.key < $1.key) }) {
    print(String(format: "%5d  %@", count, reason))
}
if list {
    print("")
    for (latex, reason) in failures { print("\(latex.replacingOccurrences(of: "\n", with: " "))\n      -> \(reason)") }
}
if let report {
    // Unbalanced fragments are usually the input's own doing (a formula split
    // by a table), not something the renderer lacks.
    let fragments: Set<String> = ["Mismatched braces.", "Missing closing brace"]
    let shown = failures.filter { !fragments.contains($0.1) }
    var groups: [(String, [String])] = []
    for (latex, reason) in shown {
        if let i = groups.firstIndex(where: { $0.0 == reason }) { groups[i].1.append(latex) } else { groups.append((reason, [latex])) }
    }
    groups.sort { $0.1.count != $1.1.count ? $0.1.count > $1.1.count : $0.0 < $1.0 }
    let sources = files.map { "`\(URL(fileURLWithPath: $0).lastPathComponent)`" }.joined(separator: ", ")
    var page = """
    # Unsupported math

    Formulas from \(sources) that the native renderer cannot typeset yet: \(failures.count) \
    of \(total) (\(String(format: "%.1f", percent))% typeset). Open this file in Quick Look to see how they \
    look: each is shown as red source, like KaTeX does. \(failures.count - shown.count) unbalanced \
    fragments from the input are left out. See [docs/math.md](../docs/math.md).

    Generated by `make math-report`; do not edit.

    """
    for (reason, items) in groups {
        page += "\n## \(reason.replacingOccurrences(of: "\\", with: "\\\\")) (\(items.count))\n\n| Source | Preview |\n|---|---|\n"
        for latex in items {
            let cell = latex.replacingOccurrences(of: "\n", with: " ").replacingOccurrences(of: "|", with: "\\|")
            let fence = cell.contains("`") ? "``" : "`"
            page += "| \(fence) \(cell) \(fence) | $\(cell)$ |\n"
        }
    }
    try! page.write(toFile: report, atomically: true, encoding: .utf8)
    print("wrote \(report)")
}
if let minimum, percent < minimum {
    print(String(format: "coverage %.1f%% is below %.1f%%", percent, minimum))
    exit(1)
}
